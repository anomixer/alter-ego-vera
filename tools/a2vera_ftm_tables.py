#!/usr/bin/env python3
"""Generate the period-to-VERA phase table used by the live FamiTone player."""
from __future__ import annotations

import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "famitone.s"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build" / "a2vera" / "ftm_tables.h"
ASM_OUT = OUT.parent / "ftm_pitch_table.s"
text = SOURCE.read_text(encoding="utf-8")
match = re.search(r"(?m)^\s*noteTable\s*:\s*;[^\r\n]*([\s\S]*)$", text)
if not match:
    raise SystemExit("could not locate NTSC noteTable in src/famitone.s")
periods = [int(v, 16) for v in re.findall(r"\$([0-9a-fA-F]+)", match.group(1))]
periods = [p for p in periods if p > 0]
if len(periods) < 60:
    raise SystemExit(f"expected at least 60 FamiTone note periods, found {len(periods)}")

# Signed pitch envelopes in the FamiTone data add directly to the NES timer.
# Cover the full table range plus the signed 6-bit envelope range.
limit = max(periods) + 64
vera_clock = 25_000_000 / 512
cpu_clock = 1_789_772.727272727
values = [0]
for period in range(1, limit + 1):
    hz = cpu_clock / (16 * (period + 1))
    values.append(max(0, min(0xFFFF, round(hz * 131072 / vera_clock))))
OUT.parent.mkdir(parents=True, exist_ok=True)
with OUT.open("w", encoding="ascii", newline="\n") as f:
    f.write("/* Generated by tools/a2vera_ftm_tables.py; do not edit. */\n")
    f.write(f"#define FTM_FREQ_TABLE_LIMIT {limit}u\n")
    f.write("static const unsigned int ftm_note_period[] = {\n")
    for i in range(0, len(periods), 12):
        f.write("    " + ",".join(f"{v}u" for v in periods[i:i+12]) + ",\n")
    f.write("};\n")
    f.write("#define FTM_PHASE_TABLE ((const unsigned int*)0x8500u)\n")
with ASM_OUT.open("w", encoding="ascii", newline="\n") as f:
    f.write('; Generated by tools/a2vera_ftm_tables.py; do not edit.\n')
    f.write('.setcpu "6502"\n.segment "FTMTABLE"\n.export _ftm_pulse_phase\n_ftm_pulse_phase:\n')
    for i in range(0, len(values), 12):
        f.write("    .word " + ",".join(f"${v:04X}" for v in values[i:i+12]) + "\n")
print(f"generated {OUT} and {ASM_OUT}: {len(values)} pulse entries through period {limit}")
